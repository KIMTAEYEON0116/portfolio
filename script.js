// 좌우 넘김: 버튼·점·스와이프(scroll-snap) 모두 같은 위치를 가리키게 한다
function bindWfCarousel(area) {
  const track = area.querySelector('.wf-car-track');
  if (!track) return;
  const slides = [...track.children];
  const dots = [...area.querySelectorAll('.wf-car-dot')];
  const prev = area.querySelector('.wf-car-btn.prev');
  const next = area.querySelector('.wf-car-btn.next');
  const counter = area.querySelector('.wf-car-count b');
  let idx = 0;
  let maxH = 0;
  const paint = () => {
    // 높이는 지금까지 본 장 중 가장 긴 장에 맞춘다.
    // 예전에는 보이는 장의 높이로 줄였는데, 다음 장이 짧거나 이미지가 아직 안 불러와졌으면
    // 페이지 전체가 짧아지면서 브라우저가 스크롤을 위로 끌어올렸다(넘길 때마다 화면이 튐).
    slides.forEach(sl => { if (sl.offsetHeight > maxH) maxH = sl.offsetHeight; });
    if (maxH) track.style.height = maxH + 'px';
    // 다음·이전 장 이미지를 미리 받아 둔다 (넘긴 순간 빈 칸이 보이지 않게)
    [idx - 1, idx + 1].forEach(i => slides[i] && slides[i].querySelectorAll('img[loading="lazy"]').forEach(im => { im.loading = 'eager'; }));
    dots.forEach((d, i) => d.classList.toggle('active', i === idx));
    if (counter) counter.textContent = idx + 1;
    prev.disabled = idx === 0;
    next.disabled = idx === slides.length - 1;
  };
  const go = i => {
    idx = Math.max(0, Math.min(slides.length - 1, i));
    track.scrollTo({ left: slides[idx].offsetLeft - track.offsetLeft, behavior: 'smooth' });
    paint();
  };
  prev.onclick = () => go(idx - 1);
  next.onclick = () => go(idx + 1);
  dots.forEach((d, i) => d.onclick = () => go(i));
  // 손가락으로 넘겼을 때도 점이 따라오게
  let t;
  track.addEventListener('scroll', () => {
    clearTimeout(t);
    t = setTimeout(() => {
      const w = track.clientWidth || 1;
      idx = Math.round(track.scrollLeft / w);
      paint();
    }, 80);
  }, { passive: true });
  slides.forEach(sl => sl.querySelectorAll('img').forEach(im => im.complete || im.addEventListener('load', paint, { once: true })));
  paint();
}

