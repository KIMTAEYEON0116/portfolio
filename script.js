/* 좌측 월 레일 — 6개월치를 스크롤할 때 현재 위치를 잃지 않도록 고정해 둔다.
   IntersectionObserver 로 화면 상단에 걸린 달을 표시한다 (rAF 에 의존하지 않는다). */
let logRailScroll = null;

function renderLogRail(d, ja, dayCnt) {
  const rail = document.getElementById('lg-rail');
  if (!rail) return;
  const secs = [...document.querySelectorAll('#lg-months .lg-mo-sec')];
  if (!secs.length) { rail.innerHTML = ''; rail.hidden = true; return; }
  rail.hidden = false;

  rail.innerHTML = d.months.map(mo => {
    const m = parseInt(mo.m, 10);
    if (!document.getElementById('lg-m-' + m)) return '';
    const days = dayCnt[m] ? `${dayCnt[m]}${ja ? '日' : '일'}` : '';
    return `<button class="lg-rb" data-m="${m}" title="${escapeHTML(ja ? mo.lb_ja : mo.lb)}">
      <b>${ja ? mo.mj : mo.m}</b><span>${mo.n}</span><i>${days}</i></button>`;
  }).join('');

  rail.querySelectorAll('.lg-rb').forEach(b => b.addEventListener('click', () => {
    const sec = document.getElementById('lg-m-' + b.dataset.m);
    if (!sec) return;
    if (sec.classList.contains('fold')) {
      sec.classList.remove('fold');
      const tg = sec.querySelector('.lg-mtg');
      if (tg) tg.textContent = '▴';
    }
    lgcScrollTo(sec);
  }));

  const btns = [...rail.querySelectorAll('.lg-rb')];
  const mark = m => btns.forEach(b => b.classList.toggle('on', b.dataset.m === String(m)));

  // IntersectionObserver 는 렌더 파이프라인이 멈춘 환경에서 콜백이 오지 않는다.
  // scroll 이벤트는 그런 환경에서도 확실히 오므로 이쪽을 쓴다.
  if (logRailScroll) window.removeEventListener('scroll', logRailScroll);
  let last = 0;
  logRailScroll = () => {
    const now = Date.now();
    if (now - last < 80) return;
    last = now;
    const y = window.scrollY + window.innerHeight * 0.18;
    let cur = secs[0];
    secs.forEach(sec => {
      if (sec.getBoundingClientRect().top + window.scrollY <= y) cur = sec;
    });
    // 마지막 달은 페이지가 끝나 판정선까지 올라오지 못하므로 바닥에서 보정한다
    if (window.innerHeight + window.scrollY >= document.documentElement.scrollHeight - 2) {
      cur = secs[secs.length - 1];
    }
    mark(cur.id.replace('lg-m-', ''));
  };
  window.addEventListener('scroll', logRailScroll, { passive: true });
  logRailScroll();
}

/* 부드러운 스크롤.
   scrollIntoView({behavior:'smooth'}) 가 조용히 무시되는 환경이 있고,
   requestAnimationFrame 자체가 돌지 않는 경우도 있다(백그라운드 탭 등).
   document.visibilityState 로는 판별되지 않으므로, 첫 프레임이 오지 않으면 즉시 이동한다. */
function lgcScrollTo(el) {
  const to = el.getBoundingClientRect().top + window.scrollY - 12;
  const from = window.scrollY, dist = to - from;
  if (Math.abs(dist) < 2) return;
  if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
    window.scrollTo(0, to); return;
  }
  let ran = false;
  const dur = Math.min(700, 220 + Math.abs(dist) * 0.22), t0 = performance.now();
  requestAnimationFrame(function step(now) {
    ran = true;
    const p = Math.min(1, (now - t0) / dur);
    const e = p < 0.5 ? 2 * p * p : 1 - Math.pow(-2 * p + 2, 2) / 2;   // easeInOutQuad
    window.scrollTo(0, from + dist * e);
    if (p < 1) requestAnimationFrame(step);
  });
  setTimeout(() => { if (!ran) window.scrollTo(0, to); }, 120);
}

/* ──────────────────────────────────────────────────────────────
   활동 캘린더 — 週=列 / 曜日=行. 훈련 기간(logdata.period) 전체를 그리고,
   아직 기록이 없는 날은 '예정'으로 둔다. 칸 크기는 CSS 로 고정하므로
   달이 늘어도 높이는 그대로이고 오른쪽으로만 자란다.
   ────────────────────────────────────────────────────────────── */
function renderLogCalendar(d, ja) {
  const host = document.getElementById('lg-cal');
  if (!host) return;
  const days = d.days || {};
  const keys = Object.keys(days).sort();
  if (!keys.length) { host.innerHTML = ''; host.hidden = true; return; }
  host.hidden = false;

  const t = i18n[currentLanguage] || {};
  const parse = s => { const p = s.split('-'); return new Date(+p[0], p[1] - 1, +p[2]); };
  const iso = x => `${x.getFullYear()}-${String(x.getMonth() + 1).padStart(2, '0')}-${String(x.getDate()).padStart(2, '0')}`;
  const mon = x => (x.getDay() + 6) % 7;          // 0=월 … 6=일

  const first = parse(keys[0]);
  const lastRec = parse(keys[keys.length - 1]);
  const end = (d.period && d.period.end) ? parse(d.period.end) : lastRec;

  // 월별 합계는 days 에서 직접 센다 — months 에 아직 없는 달도 칸은 그려야 한다
  const per = {};
  keys.forEach(k => { const m = +k.slice(5, 7); per[m] = (per[m] || 0) + days[k][0]; });

  let mx = 1;
  keys.forEach(k => { if (days[k][0] > mx) mx = days[k][0]; });
  const lv = n => n <= 0 ? 0 : Math.min(4, 1 + Math.floor((n - 1) * 4 / mx));

  const WD = ja ? ['月', '火', '水', '木', '金', '土', '日']
                : ['월', '화', '수', '목', '금', '토', '일'];
  const MU = ja ? '月' : '월', DU = ja ? '日' : '일', CU = ja ? '件' : '건';

  const blocks = [];
  const cur = new Date(first.getFullYear(), first.getMonth(), 1);
  while (cur <= end) {
    const y = cur.getFullYear(), m = cur.getMonth(), m1 = m + 1;
    const nd = new Date(y, m1, 0).getDate();
    let cells = '<i class="lgc-c pad"></i>'.repeat(mon(new Date(y, m, 1)));
    for (let dd = 1; dd <= nd; dd++) {
      const x = new Date(y, m, dd);
      if (x < first || x > end) { cells += '<i class="lgc-c pad"></i>'; continue; }
      const rec = days[iso(x)];
      const n = rec ? rec[0] : 0;
      if (!n && x > lastRec) {
        cells += `<i class="lgc-c soon" data-tip="${m1}${MU} ${dd}${DU} · ${t.log_cal_soon || ''}"></i>`;
      } else {
        const tip = n ? `${m1}${MU} ${dd}${DU} · ${ja ? '日誌' : '일지'} ${n}${CU}`
                      : `${m1}${MU} ${dd}${DU} · ${ja ? '記録なし' : '기록 없음'}`;
        cells += `<i class="lgc-c l${lv(n)}" data-tip="${tip}"${n ? ` data-m="${m1}"` : ''}></i>`;
      }
    }
    blocks.push(`<div class="lgc-mo">
      <div class="lgc-mh"${per[m1] ? ` data-m="${m1}"` : ''}>
        <b>${m1}${MU}</b><span>${per[m1] ? per[m1] + CU : '—'}</span></div>
      <div class="lgc-wd">${WD.map(w => `<i>${w}</i>`).join('')}</div>
      <div class="lgc-gd">${cells}</div>
    </div>`);
    cur.setMonth(cur.getMonth() + 1);
  }

  // 캡션: 기록이 있는 구간의 '훈련 평일' 대비 비율
  let wd = 0;
  for (let x = new Date(first); x <= lastRec; x.setDate(x.getDate() + 1)) {
    if (mon(x) < 5) wd++;
  }
  const pct = wd ? Math.round(keys.length / wd * 100) : 0;
  const cap = ja
    ? `訓練の平日 ${wd}日のうち <b>${keys.length}日</b>（${pct}%）に記録。`
    : `훈련 평일 ${wd}일 중 <b>${keys.length}일</b>(${pct}%)에 기록.`;

  host.innerHTML = `
    <div class="lgc-head">
      <h4>${t.log_cal_title || (ja ? '活動カレンダー' : '활동 캘린더')}</h4>
      <div class="lgc-lgd">${t.log_cal_less || ''}
        <i class="lgc-c l0"></i><i class="lgc-c l1"></i><i class="lgc-c l2"></i>
        <i class="lgc-c l3"></i><i class="lgc-c l4"></i>${t.log_cal_more || ''}
        <i class="lgc-c soon"></i>${t.log_cal_soon || ''}</div>
    </div>
    <div class="lgc-row">${blocks.join('')}</div>
    <p class="lgc-cap">${cap}</p>
    <div class="lgc-tip" id="lgc-tip"></div>`;

  const tip = document.getElementById('lgc-tip');
  host.querySelectorAll('.lgc-c[data-tip]').forEach(el => {
    el.addEventListener('mouseenter', () => {
      const b = el.getBoundingClientRect(), h = host.getBoundingClientRect();
      tip.textContent = el.dataset.tip;
      tip.style.left = (b.left - h.left + b.width / 2) + 'px';
      tip.style.top = (b.top - h.top) + 'px';
      tip.classList.add('on');
    });
    el.addEventListener('mouseleave', () => tip.classList.remove('on'));
  });
  // 기록이 있는 날·월 이름을 누르면 그 달 섹션으로 (접혀 있으면 펼친다)
  host.querySelectorAll('[data-m]').forEach(el =>
    el.addEventListener('click', () => {
      const sec = document.getElementById('lg-m-' + el.dataset.m);
      if (!sec) return;
      if (sec.classList.contains('fold')) {
        sec.classList.remove('fold');
        const tg = sec.querySelector('.lg-mtg');
        if (tg) tg.textContent = '▴';
      }
      lgcScrollTo(sec);
      sec.classList.add('lgc-hit');
      setTimeout(() => sec.classList.remove('lgc-hit'), 1200);
    }));
}

