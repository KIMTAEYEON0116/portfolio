// `코드`·**강조**·<br> 표기를 태그로 (XSS 방지 escape 후 허용 태그만 복원)

/* 담당 업무를 단계별로 접는다.
   role 은 "머리말<br><br>**① 제목** — 내용<br><br>…" 형식이다.
   제목만 세워 두고 내용은 눌렀을 때 편다. */
function buildRoleHtml(role) {
  const parts = String(role || '').split('<br><br>');
  const intro = parts.shift() || '';
  const steps = parts.filter(Boolean);
  if (!steps.length) return inlineCode(role);          // 번호가 없는 글은 그대로

  const rows = steps.map(p => {
    const m = p.match(/^\*\*(.+?)\*\*\s*(?:—|-)?\s*([\s\S]*)$/);
    const head = m ? m[1] : p;
    const body = m ? m[2].trim() : '';
    return `<li class="role-step">
      <button type="button" class="role-step-h">
        <span>${inlineCode(head)}</span>${body ? '<i>▾</i>' : ''}
      </button>
      ${body ? `<div class="role-step-b">${inlineCode(body)}</div>` : ''}
    </li>`;
  }).join('');

  const all = currentLanguage === 'ja' ? 'すべて開く' : '모두 펼치기';
  return `<p class="role-intro">${inlineCode(intro)}</p>
    <ol class="role-steps">${rows}</ol>
    <button type="button" class="role-all">${all} ▾</button>`;
}

function bindRoleSteps(root) {
  const ja = currentLanguage === 'ja';
  root.querySelectorAll('.role-step-h').forEach(b => b.addEventListener('click', () => {
    b.parentElement.classList.toggle('open');
  }));
  const all = root.querySelector('.role-all');
  if (!all) return;
  all.addEventListener('click', () => {
    const steps = [...root.querySelectorAll('.role-step')];
    const open = steps.some(x => !x.classList.contains('open'));
    steps.forEach(x => x.classList.toggle('open', open));
    all.textContent = (open ? (ja ? 'すべて閉じる' : '모두 접기')
                            : (ja ? 'すべて開く' : '모두 펼치기')) + (open ? ' ▴' : ' ▾');
  });
}

function inlineCode(t) {
  return escapeHTML(t || '')
    .replace(/&lt;br\s*\/?&gt;/gi, '<br>')
    .replace(/`([^`]+)`/g, '<code>$1</code>')
    .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>');
}

