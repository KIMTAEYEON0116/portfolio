function navigateTo(sectionId) {
  stopAllVideos();
  if (sectionId === 'log-view' && typeof renderLogPage === 'function') {
    setTimeout(renderLogPage, 0);
  }

  const currentActive = document.querySelector('.view-section.active');
  if (currentActive && currentActive.id !== sectionId) {
    previousView = currentActive.id;
  }
  currentView = sectionId;

  // 모든 섹션 비활성화
  const sections = document.querySelectorAll('.view-section');
  sections.forEach(sec => {
    sec.classList.remove('active');
  });

  // 선택한 섹션 활성화
  const targetSec = document.getElementById(sectionId);
  if (targetSec) {
    targetSec.classList.add('active');
    window.scrollTo({ top: 0, behavior: 'smooth' });
  }
}

function goBack() {
  if (previousView && previousView !== currentView) {
    navigateTo(previousView);
  } else {
    navigateTo('main-view');
  }
}


// 4. 방명록 등록 핸들러 (FastAPI 연동)
async function handleGuestbookSubmit(event) {
  event.preventDefault();

  const title = document.getElementById('gb-title').value.trim();
  const author = document.getElementById('gb-author').value.trim();
  const content = document.getElementById('gb-content').value.trim();

  if (!title || !content) return;

  const submitBtn = document.querySelector('.submit-btn');
  if (submitBtn) { submitBtn.disabled = true; submitBtn.style.opacity = '0.6'; }

  let res;
  try {
    res = await fetch('/api/guestbook', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ title, author, content, lang: currentLanguage })
    });
  } catch (err) {
    res = null;   // 서버에 닿지 못함 → 아래 localStorage 폴백
  }

  // 서버가 응답은 했지만 거절한 경우(너무 잦은 등록·입력 오류 등):
  // 예전에는 이것도 '저장됨'처럼 브라우저에만 넣어, 방문자는 남겼다고 믿는데 주인은 못 봤다.
  if (res && !res.ok) {
    const ja = currentLanguage === 'ja';
    alert(res.status === 429
      ? (ja ? '短時間に投稿が集中しています。しばらくしてからもう一度お試しください。' : '등록이 너무 잦습니다. 잠시 후 다시 시도해 주세요.')
      : (ja ? '投稿できませんでした。入力内容をご確認ください。' : '등록하지 못했습니다. 입력 내용을 확인해 주세요.'));
    if (submitBtn) { submitBtn.disabled = false; submitBtn.style.opacity = '1'; }
    return;
  }

  try {
    if (!res) throw new Error('서버 미연결');
    document.getElementById('guestbook-form').reset();
    await renderGuestbook();
  } catch (err) {
    // 서버 미연결 시 LocalStorage 폴백
    console.warn('[방명록] 서버 연결 실패, localStorage 사용:', err.message);
    const dateStr = new Date().toLocaleDateString('ko-KR', {
      year: 'numeric', month: '2-digit', day: '2-digit'
    }).replace(/\. /g, '.').replace(/\.$/, '');
    const newMessage = { title, author: author || '匿名', content, date: dateStr };
    const currentList = JSON.parse(localStorage.getItem('guestbook_messages')) || [];
    currentList.unshift(newMessage);
    localStorage.setItem('guestbook_messages', JSON.stringify(currentList));
    document.getElementById('guestbook-form').reset();
    renderGuestbook();
  } finally {
    if (submitBtn) { submitBtn.disabled = false; submitBtn.style.opacity = '1'; }
  }
}

// 5. 방명록 렌더링 (FastAPI 연동)
async function renderGuestbook() {
  const listContainer = document.getElementById('guestbook-list');
  const countBadge = document.getElementById('guestbook-count');

  const loadingMsg = currentLanguage === 'ja' ? '読み込み中...' : '불러오는 중...';
  listContainer.innerHTML = `<p style="text-align:center;color:#888;padding:10px 0;font-size:0.85rem;">${loadingMsg}</p>`;

  let messages = [];
  try {
    const res = await fetch('/api/guestbook');
    if (!res.ok) throw new Error('서버 오류');
    messages = await res.json();
  } catch (err) {
    console.warn('[방명록] 서버 연결 실패, localStorage 사용:', err.message);
    messages = JSON.parse(localStorage.getItem('guestbook_messages')) || [];
  }

  countBadge.textContent = messages.length;
  listContainer.innerHTML = '';

  if (messages.length === 0) {
    const noMsg = currentLanguage === 'ja' ? '最初のゲストブックを残してみてください！' : '첫 방명록을 남겨보세요!';
    listContainer.innerHTML = `<p style="font-size: 0.85rem; color:#888; text-align:center; padding: 20px 0;">${noMsg}</p>`;
    return;
  }

  messages.forEach(msg => {
    const item = document.createElement('div');
    item.className = 'guestbook-item';
    const datePrefix = currentLanguage === 'ja' ? '作成日' : '작성일';
    const authorPrefix = currentLanguage === 'ja' ? '作成者' : '작성자';
    item.innerHTML = `
      <div class="guestbook-item-header">
        <span>${datePrefix}: ${escapeHTML(msg.date)}</span>
        <span>${authorPrefix}: ${escapeHTML(msg.author === '匿名' && currentLanguage === 'ko' ? '익명' : msg.author)}</span>
      </div>
      <div class="guestbook-item-title">${escapeHTML(msg.title)}</div>
      <div class="guestbook-item-content">${escapeHTML(msg.content)}</div>
    `;
    listContainer.appendChild(item);
  });
}

// 6. XSS 방지를 위한 HTML Escape
// 한국어 목적격 조사: 마지막 글자에 받침이 있으면 「을」, 없으면 「를」
// (괄호·공백은 건너뛰고, 영문은 발음 기준으로 어림한다: Club → 을)
function koObjectParticle(word) {
  const w = String(word || '').replace(/[\s)）」』\]]+$/, '');
  const ch = w.slice(-1);
  const code = ch.charCodeAt(0);
  if (code >= 0xAC00 && code <= 0xD7A3) return (code - 0xAC00) % 28 ? '을' : '를';
  if (/[0-9]/.test(ch)) return '013678'.includes(ch) ? '을' : '를';
  if (/[a-z]/i.test(ch)) return /[bklmnpt]/i.test(ch) ? '을' : '를';
  return '를';
}

function escapeHTML(str) {
  if (!str) return '';
  return str.replace(/[&<>'"]/g,
    tag => ({
      '&': '&amp;',
      '<': '&lt;',
      '>': '&gt;',
      "'": '&#39;',
      '"': '&quot;'
    }[tag] || tag)
  );
}

