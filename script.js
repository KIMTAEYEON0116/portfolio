function showMediaSlide() {
  const viewport = document.getElementById('project-media-viewport');
  const item = currentProjectMedia[currentMediaIndex];
  viewport.innerHTML = '';

  if (item) {
    if (item.type === 'video') {
      const video = document.createElement('video');
      video.src = item.src;
      video.controls = true;
      video.playsInline = true;
      viewport.appendChild(video);
    } else if (item.type === 'youtube' || (typeof item.src === 'string' && (item.src.includes('youtube.com') || item.src.includes('youtu.be')))) {
      const iframe = document.createElement('iframe');
      let embedUrl = item.src;
      if (embedUrl.includes('youtu.be/') || embedUrl.includes('watch?v=')) {
        let videoId = '';
        if (embedUrl.includes('youtu.be/')) {
          videoId = embedUrl.split('youtu.be/')[1].split(/[?#]/)[0];
        } else {
          const urlParts = embedUrl.split('v=');
          if (urlParts.length > 1) {
            videoId = urlParts[1].split('&')[0];
          }
        }
        if (videoId) {
          embedUrl = `https://www.youtube.com/embed/${videoId}`;
        }
      }
      iframe.src = embedUrl;
      iframe.frameBorder = "0";
      iframe.allow = "accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture; web-share";
      iframe.allowFullscreen = true;
      viewport.appendChild(iframe);
    } else {
      const img = document.createElement('img');
      img.src = item.src;
      img.alt = currentLanguage === 'ja'
        ? `${currentMediaAltBase}代表画像 ${currentMediaIndex + 1}`
        : `${currentMediaAltBase} 대표 이미지 ${currentMediaIndex + 1}`;
      viewport.appendChild(img);
    }
  }

  // 캡처가 없는 프로젝트(포트폴리오)는 미디어 칸을 접고 설명이 전폭을 쓰게 한다.
  // 높이를 고정해 뒀기 때문에 그냥 두면 808px 짜리 빈 상자가 남는다.
  const upper = document.querySelector('.project-upper-section');
  const mediaBox = document.querySelector('.project-media-box');
  const noMedia = currentProjectMedia.length === 0;
  if (mediaBox) mediaBox.classList.toggle('is-empty', noMedia);
  if (upper) upper.classList.toggle('no-media', noMedia);

  // 실제 고객사 안건처럼 소스를 공개할 수 없는 프로젝트는 그 사실을 캡처 아래에 밝힌다.
  const noteEl = document.getElementById('media-client-note');
  if (noteEl) {
    const pid = document.querySelector('.project-tab.active')?.id.replace('p-tab-', '');
    const note = pid && projectDatabase[pid] && projectDatabase[pid].clientNote;
    if (note) {
      noteEl.textContent = currentLanguage === 'ja' ? note.ja : note.ko;
      noteEl.hidden = false;
    } else {
      noteEl.hidden = true;
    }
  }

  const hasMultiple = currentProjectMedia.length > 1;
  document.getElementById('media-prev-btn').classList.toggle('is-hidden', !hasMultiple);
  document.getElementById('media-next-btn').classList.toggle('is-hidden', !hasMultiple);

  const dotsContainer = document.getElementById('media-dots');
  dotsContainer.innerHTML = '';
  if (hasMultiple) {
    currentProjectMedia.forEach((_, idx) => {
      const dot = document.createElement('button');
      dot.type = 'button';
      dot.className = 'media-dot' + (idx === currentMediaIndex ? ' active' : '');
      dot.setAttribute('aria-label', `${idx + 1}`);
      dot.onclick = () => { currentMediaIndex = idx; showMediaSlide(); };
      dotsContainer.appendChild(dot);
    });
  }
}

function moveProjectMedia(direction) {
  if (currentProjectMedia.length < 2) return;
  currentMediaIndex = (currentMediaIndex + direction + currentProjectMedia.length) % currentProjectMedia.length;
  showMediaSlide();
}


