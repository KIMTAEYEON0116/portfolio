// 다국어 전환 및 적용 핵심 로직
function setLanguage(lang) {
  const oldLang = currentLanguage;
  currentLanguage = lang;
  localStorage.setItem('portfolio_lang', lang);

  // 다국어 토글 버튼 활성 클래스 부여
  document.querySelectorAll('.lang-btn').forEach(btn => btn.classList.remove('active'));
  const activeBtn = document.getElementById(`btn-lang-${lang}`);
  if (activeBtn) activeBtn.classList.add('active');

  // HTML lang 속성 변경
  document.documentElement.lang = lang;

  // HTML title 태그 갱신
  if (i18n[lang] && i18n[lang].page_title) {
    document.title = i18n[lang].page_title;
    if (typeof updateDocTitle === 'function') setTimeout(updateDocTitle, 0);
  }

  // 정적 텍스트 번역 적용 (타이핑 커서 span을 보호)
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (i18n[lang] && i18n[lang][key]) {
      // 타이핑 커서 span은 유지
      const cursorEl = el.querySelector('.typing-cursor');
      el.innerHTML = i18n[lang][key];
      if (cursorEl) el.appendChild(cursorEl);
    }
  });

  // 플레이스홀더 번역 적용
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (i18n[lang] && i18n[lang][key]) {
      el.placeholder = i18n[lang][key];
    }
  });

  if (localStorage.getItem('guestbook_messages')) {
    const savedGb = localStorage.getItem('guestbook_messages');
    if (savedGb === JSON.stringify(defaultGuestbook[oldLang])) {
      localStorage.setItem('guestbook_messages', JSON.stringify(defaultGuestbook[lang]));
    }
  } else {
    localStorage.setItem('guestbook_messages', JSON.stringify(defaultGuestbook[lang]));
  }

  // 화면 리렌더링
  if (typeof renderGuestbook === 'function') renderGuestbook();

  // 트러블슈팅 탭이 열려 있으면 언어에 맞춰 다시 그린다
  const ttab = document.getElementById('inner-tab-trouble');
  if (ttab && ttab.classList.contains('active') && typeof renderTroubleArea === 'function') {
    renderTroubleArea();
  }

  // 활성화된 프로젝트 상세 리렌더링
  const activeProjTab = document.querySelector('.project-tab.active');
  if (activeProjTab) {
    const activeProjId = activeProjTab.id.replace('p-tab-', '');
    if (typeof renderProject === 'function') renderProject(activeProjId);
  } else {
    if (typeof renderProject === 'function') renderProject('hospital');
  }

  // 일지 페이지 재렌더링
  if (typeof renderLogPage === 'function') renderLogPage();
}


