// 내부 탭 전환 (개요 ↔ 기획 문서 ↔ 페이지 구성 ↔ 데모 영상 ↔ UI 프로토타입)
function switchProjectInnerTab(tabName, silent = false) {
  stopAllVideos();
  const overviewArea = document.getElementById('project-overview-area');
  const embedArea = document.getElementById('project-embed-area');
  const demoArea = document.getElementById('project-demo-area');
  const structureArea = document.getElementById('project-structure-area');
  const prototypeArea = document.getElementById('project-prototype-area');
  const tabOverview = document.getElementById('inner-tab-overview');
  const tabDocs = document.getElementById('inner-tab-docs');
  const tabDemo = document.getElementById('inner-tab-demo');
  const tabStructure = document.getElementById('inner-tab-structure');
  const tabPrototype = document.getElementById('inner-tab-prototype');

  if (!overviewArea || !embedArea) return;

  // 모든 영역 숨김, 모든 탭 비활성화
  overviewArea.style.display = 'none';
  embedArea.style.display = 'none';
  if (demoArea) demoArea.style.display = 'none';
  if (structureArea) structureArea.style.display = 'none';
  if (prototypeArea) prototypeArea.style.display = 'none';
  if (tabOverview) tabOverview.classList.remove('active');
  if (tabDocs) tabDocs.classList.remove('active');
  if (tabDemo) tabDemo.classList.remove('active');
  if (tabStructure) tabStructure.classList.remove('active');
  if (tabPrototype) tabPrototype.classList.remove('active');
  const tabTrouble = document.getElementById('inner-tab-trouble');
  if (tabTrouble) tabTrouble.classList.remove('active');

  if (tabName === 'trouble') {
    if (tabTrouble) tabTrouble.classList.add('active');
    embedArea.style.display = 'block';
    renderTroubleArea();
    return;
  }

  if (tabName === 'overview') {
    overviewArea.style.display = 'block';
    if (tabOverview) tabOverview.classList.add('active');
  } else if (tabName === 'docs') {
    embedArea.style.display = 'block';
    if (tabDocs) tabDocs.classList.add('active');
    if (!silent) renderEmbedArea();
  } else if (tabName === 'structure') {
    if (structureArea) structureArea.style.display = 'block';
    if (tabStructure) tabStructure.classList.add('active');
    if (!silent) renderStructureArea();
  } else if (tabName === 'demo') {
    if (demoArea) demoArea.style.display = 'block';
    if (tabDemo) tabDemo.classList.add('active');
    if (!silent) renderDemoArea();
  } else if (tabName === 'prototype') {
    if (prototypeArea) prototypeArea.style.display = 'block';
    if (tabPrototype) tabPrototype.classList.add('active');
    if (!silent) renderPrototypeArea();
  }
}

