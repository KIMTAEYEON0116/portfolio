// 주소(URL) 라우팅
//   화면마다 주소를 붙인다: #/about · #/log · #/contact · #/project/hospital/trouble
//   - 면접관이 특정 프로젝트 링크를 그대로 공유할 수 있다
//   - 새로고침해도 보던 화면이 유지된다
//   - 브라우저 뒤로가기가 사이트 밖으로 튕기지 않고 이전 화면으로 간다
// ==========================================================================
const ROUTE_VIEWS = { '': 'main-view', about: 'about-view', log: 'log-view', contact: 'contact-view', project: 'project-view' };
const ROUTE_PROJECTS = ['hospital', 'gakong', 'typing', 'portfolio'];
let applyingRoute = false;
let routeSyncPending = false;

function activeProjectId() {
  const t = document.querySelector('.project-tab.active');
  return t ? t.id.replace('p-tab-', '') : 'hospital';
}
function activeInnerTab() {
  const t = document.querySelector('.project-inner-tab.active');
  return t ? t.id.replace('inner-tab-', '') : 'overview';
}
function currentRouteHash() {
  if (currentView === 'project-view') {
    const tab = activeInnerTab();
    return '#/project/' + activeProjectId() + (tab && tab !== 'overview' ? '/' + tab : '');
  }
  const key = Object.keys(ROUTE_VIEWS).find(k => ROUTE_VIEWS[k] === currentView) || '';
  return '#/' + key;
}
// 브라우저 탭 제목: 「健康診断予約 | 金兌衍（キム・テヨン） | ポートフォリオ」
function updateDocTitle() {
  const t = i18n[currentLanguage] || {};
  const base = t.page_title || document.title;
  const ja = currentLanguage === 'ja';
  const names = {
    'about-view': ja ? '自己紹介' : '자기소개',
    'log-view': ja ? '日誌' : '일지',
    'contact-view': ja ? '連絡先' : '연락처'
  };
  let sub = names[currentView] || '';
  if (currentView === 'project-view') {
    const tab = document.querySelector('.project-tab.active');
    sub = tab ? tab.textContent.trim() : '';
  }
  document.title = sub ? sub + ' | ' + base : base;
  // 화면 읽기 프로그램용 이름도 화면 언어에 맞춘다
  document.querySelectorAll('.nav-icon-btn').forEach(el => {
    const back = (el.getAttribute('onclick') || '').includes('goBack');
    el.setAttribute('aria-label', back ? (ja ? '前のページへ戻る' : '이전 페이지') : (ja ? 'ホームへ' : '홈으로'));
  });
}
// 한 번의 클릭이 navigateTo → switchProjectTab → switchProjectInnerTab 을 연달아 불러도
// 기록은 마지막 상태로 한 번만 남긴다
function scheduleRouteSync() {
  if (applyingRoute || routeSyncPending) return;
  routeSyncPending = true;
  setTimeout(() => {
    routeSyncPending = false;
    const h = currentRouteHash();
    const now = location.hash || '#/';
    if (now !== h) history.pushState(null, '', location.pathname + location.search + (h === '#/' ? '' : h));
    updateDocTitle();
  }, 0);
}
function applyRoute() {
  const parts = location.hash.replace(/^#\/?/, '').split('/').filter(Boolean);
  const view = ROUTE_VIEWS[parts[0] || ''] || 'main-view';
  applyingRoute = true;
  try {
    if (view === 'project-view') {
      const pid = ROUTE_PROJECTS.includes(parts[1]) ? parts[1] : activeProjectId();
      navigateTo('project-view');
      switchProjectTab(pid);
      const tab = parts[2];
      const el = tab && document.getElementById('inner-tab-' + tab);
      if (el && el.style.display !== 'none') switchProjectInnerTab(tab);
    } else {
      navigateTo(view);
    }
  } finally {
    applyingRoute = false;
  }
  updateDocTitle();
}
window.addEventListener('popstate', applyRoute);

// 기존 화면 전환 함수에 주소 갱신을 덧붙인다 (onclick 에서 부르는 이름 그대로)
(function wrapForRouting() {
  const _nav = navigateTo, _proj = switchProjectTab, _inner = switchProjectInnerTab;
  navigateTo = function (id) { _nav(id); scheduleRouteSync(); };
  switchProjectTab = function (pid) { _proj(pid); scheduleRouteSync(); };
  switchProjectInnerTab = function (tab, silent) { _inner(tab, silent); if (!silent) scheduleRouteSync(); };
})();

// div·span 으로 만든 버튼(프로젝트 탭·태그 필터)도 Enter/Space 로 누를 수 있게
document.addEventListener('keydown', e => {
  if (e.key !== 'Enter' && e.key !== ' ') return;
  const el = e.target;
  if (el && el.getAttribute && el.getAttribute('role') === 'button' && el.tagName !== 'BUTTON' && el.tagName !== 'A') {
    e.preventDefault();
    el.click();
  }
});
